func T(lang Lang, key string, args ...interface{}) string {
	if lang == "" {
		lang = LangFA
	}
	m, ok := translations[lang]
	if !ok {
		m = translations[LangFA]
	}
	s, ok := m[key]
	if !ok {
		return key
	}
	if len(args) > 0 {
		return fmt.Sprintf(s, args...)
	}
	return s
}

func LangLabel(l Lang) string {
	switch l {
	case LangFA:
		return "🇮🇷 فارسی"
	case LangEN:
		return "🇬🇧 English"
	}
	return "🌍"
}
